const {chromium}=require('C:/Users/EZEN/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const errors=[],failures=[],checks=[];
 try{
  const page=await browser.newPage({viewport:{width:1440,height:960}});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('requestfailed',r=>failures.push(r.url()));
  page.on('response',r=>{if(r.status()>=400)failures.push(`${r.status()} ${r.url()}`)});
  await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
  assert.equal(await page.locator('.tape').count(),5);
  await page.locator('.tape-about .tape-orientation').screenshot({path:path.resolve('output/portfolio-v31-topview-cassette.png')});
  await page.getByRole('button',{name:'01 ABOUT ME 테이프 넣기',exact:true}).click();
  assert.equal(await page.locator('.tape').count(),4);
  const snapshot=()=>page.locator('.player [data-part="hub"]').evaluateAll(hubs=>hubs.map(hub=>{
   const m=hub.getScreenCTM(),box=hub.querySelector('[data-part="fixed-light"]').getBBox();
   return {angle:Number(hub.dataset.angle),axis:{x:m.e,y:m.f},scaleX:Math.hypot(m.a,m.b),scaleY:Math.hypot(m.c,m.d),fixed:hub.querySelector('[data-part="fixed-light"]').outerHTML,box:{x:box.x,y:box.y,width:box.width,height:box.height},radius:Number(hub.parentElement.querySelector('[data-part="pack-surface"]').getAttribute('r'))};
  }));
  const idle=await snapshot();
  assert.equal(idle.length,2);
  assert.ok(idle.every(h=>Math.abs(h.box.width-h.box.height)<.001&&Math.abs(h.scaleX-h.scaleY)<.001));
  await page.screenshot({path:path.resolve('output/portfolio-v31-desktop.png'),fullPage:true});
  await page.locator('.player').screenshot({path:path.resolve('output/portfolio-v31-player-stopped.png')});
  await page.getByRole('button',{name:'재생',exact:true}).click();
  await page.locator('dialog[open]').waitFor();
  await page.keyboard.press('Escape');
  const before=await snapshot();
  await page.waitForTimeout(600);
  const playing=await snapshot();
  assert.ok(playing.every((h,i)=>h.angle>before[i].angle));
  assert.ok(Math.abs((playing[0].angle-before[0].angle)-(playing[1].angle-before[1].angle))>.05,'Different winding amounts give different angular speeds');
  assert.ok(playing.every((h,i)=>Math.abs(h.axis.x-idle[i].axis.x)<.001&&Math.abs(h.axis.y-idle[i].axis.y)<.001),'Axes do not wobble');
  assert.ok(playing.every((h,i)=>h.fixed===idle[i].fixed),'Material light layer never rotates');
  assert.ok(playing.every(h=>Math.abs(h.scaleX-h.scaleY)<.001),'Reels stay circular while playing');
  await page.locator('.player').screenshot({path:path.resolve('output/portfolio-v31-player-playing.png')});
  checks.push('same circular geometry at rest and during motion','spindle centers stationary','stationary surface light','independent angular speeds');
  await page.getByRole('button',{name:'정지',exact:true}).click();
  await page.waitForTimeout(30);
  const stopped=await snapshot();
  await page.waitForTimeout(180);
  assert.deepEqual((await snapshot()).map(h=>[h.angle,h.radius]),stopped.map(h=>[h.angle,h.radius]));
  await page.getByRole('button',{name:'되감기',exact:true}).click();
  await page.waitForTimeout(500);
  const rewind=await snapshot();
  assert.ok(rewind.every((h,i)=>h.angle<stopped[i].angle));
  assert.ok(rewind[0].radius>stopped[0].radius&&rewind[1].radius<stopped[1].radius);
  await page.getByRole('button',{name:'빨리 감기',exact:true}).click();
  await page.waitForTimeout(500);
  const forward=await snapshot();
  assert.ok(forward.every((h,i)=>h.angle>rewind[i].angle));
  assert.ok(forward[0].radius<rewind[0].radius&&forward[1].radius>rewind[1].radius);
  checks.push('stop freezes hub and winding','rewind reverses both hubs and winding','forward resumes winding in opposite direction');
  await page.getByRole('button',{name:'꺼내기 ⏏',exact:true}).click();
  assert.equal(await page.locator('.tape').count(),5);
  assert.equal(await page.locator('.tape [data-part="hub"][data-view="orthographic"]').count(),10);
  checks.push('same top-view hubs on returned desk tapes');
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
  await mobile.getByRole('button',{name:'03 DESIGN 테이프 넣기',exact:true}).click();
  await mobile.getByRole('button',{name:'재생',exact:true}).click();
  await mobile.keyboard.press('Escape');
  await mobile.waitForTimeout(300);
  assert.ok(await mobile.locator('.player [data-part="hub"]').evaluateAll(hubs=>hubs.every(h=>Number(h.dataset.angle)>0)));
  assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await mobile.locator('.player').screenshot({path:path.resolve('output/portfolio-v31-mobile-playing.png')});
  checks.push('mobile tap/play and no horizontal overflow');
  const reduced=await browser.newPage({viewport:{width:1366,height:768},reducedMotion:'reduce'});
  await reduced.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
  await reduced.getByRole('button',{name:'01 ABOUT ME 테이프 넣기',exact:true}).click();
  await reduced.getByRole('button',{name:'재생',exact:true}).click();
  await reduced.keyboard.press('Escape');
  await reduced.waitForTimeout(300);
  assert.ok(await reduced.locator('.player [data-part="hub"]').evaluateAll(hubs=>hubs.every(h=>Number(h.dataset.angle)===0)));
  assert.equal(await reduced.locator('.portfolio').evaluate(e=>e.getBoundingClientRect().height),768);
  checks.push('reduced motion honored','100vh main retained');
  assert.deepEqual(errors,[]);assert.deepEqual(failures,[]);
  const report={passed:true,checks,axes:idle.map(h=>h.axis),idleAngles:idle.map(h=>h.angle),playAngles:playing.map(h=>h.angle),rewindAngles:rewind.map(h=>h.angle),forwardAngles:forward.map(h=>h.angle),errors,failures};
  fs.writeFileSync(path.resolve('output/reel-motion-v31-qa.json'),JSON.stringify(report,null,2));
  process.stdout.write(JSON.stringify(report));
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
