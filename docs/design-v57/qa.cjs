const {chromium}=require('C:/Users/EZEN/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const fs=require('node:fs'),assert=require('node:assert/strict')
;(async()=>{
 const out='C:/bin/portfolio/docs/design-v57';fs.mkdirSync(out,{recursive:true})
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true})
 const checks=[]
 try{
  for(const [name,width,height] of [['desktop',1440,1000],['mobile',390,844]]){
   const page=await browser.newPage({viewport:{width,height},reducedMotion:'reduce'});const errors=[];page.on('pageerror',e=>errors.push(e.message))
   await page.goto('http://127.0.0.1:5173/')
   await page.getByRole('button',{name:'보관함 목록 열기'}).click()
   for(const title of ['01 ABOUT ME','02 TEAM PLAY','03 DESIGN','04 BRANDING','05 NEXT TRACK'])await page.getByRole('button',{name:`${title} 보관함에 넣기`,exact:true}).click()
   await page.keyboard.press('Escape')
   await page.locator('.archive').scrollIntoViewIfNeeded()
   await page.evaluate(()=>document.activeElement?.blur())
   await page.locator('.archive').screenshot({path:`${out}/home-${name}.png`})
   const labels=await page.locator('.archive [data-layer="case-number-labels"] text').evaluateAll(nodes=>nodes.map(n=>({number:n.textContent,font:n.getAttribute('font-size'),fill:n.getAttribute('fill')})))
   assert.equal(labels.length,5)
   const label=page.locator('.archive [data-number="01"]'),bounds=await label.boundingBox()
   await page.mouse.click(bounds.x+bounds.width/2,bounds.y+bounds.height/2)
   assert.equal(await page.locator('.tape-about').count(),1)
   assert.equal(await page.locator('.archive [data-stored-id="about"]').count(),0)
   await page.locator('.tape-about').click()
   await page.getByRole('button',{name:'재생',exact:true}).click()
   await page.locator('.story-reader').waitFor()
   if(width<761)await page.locator('.reader-shelf-toggle').click()
   await page.locator('.reader-shelf').scrollIntoViewIfNeeded()
   await page.locator('.reader-shelf-art').screenshot({path:`${out}/reader-${name}.png`})
   const readerLabels=await page.locator('.reader-shelf-art [data-layer="case-number-labels"] text').evaluateAll(nodes=>nodes.map(n=>({number:n.textContent,font:n.getAttribute('font-size'),fill:n.getAttribute('fill')})))
   assert.deepEqual(readerLabels,labels)
   const number03=await page.locator('.reader-shelf-art [data-number="03"]').boundingBox()
   await page.mouse.click(number03.x+number03.width/2,number03.y+number03.height/2)
   assert.equal(await page.locator('.reader-case[data-slot="2"]').isDisabled(),true)
   assert.deepEqual(errors,[])
   checks.push({name,identicalLabelAppearance:true,homeNumberTake:true,readerNumberSwap:true,errors})
   await page.close()
  }
  fs.writeFileSync(out+'/qa.json',JSON.stringify(checks,null,2));console.log(JSON.stringify(checks,null,2))
 }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
