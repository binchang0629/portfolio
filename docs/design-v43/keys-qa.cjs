const {chromium}=require('C:/Users/EZEN/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const out='C:/bin/portfolio/docs/design-v43/';
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const errors=[],checks=[];
 try{
  const page=await browser.newPage({viewport:{width:1440,height:960},reducedMotion:'reduce'});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
  await page.locator('.tape-about').click();
  await page.locator('.player').evaluate(p=>Object.assign(p.style,{width:'800px',left:'400px',top:'200px',zIndex:'6'}));
  const key=idx=>page.locator(`.mechanical-key[data-key-index="${idx}"]`);
  const latched=()=>page.locator('.mechanical-key[data-latched="true"]').count();
  const matrix=idx=>key(idx).locator('.mechanical-key-face').evaluate(el=>getComputedStyle(el).transform);
  await page.locator('.player').screenshot({path:out+'keys-released.png'});
  await page.getByRole('button',{name:'재생',exact:true}).click();
  await page.keyboard.press('Escape');
  assert.equal(await key(0).getAttribute('data-latched'),'true');assert.equal(await latched(),1);
  assert.equal(await matrix(0),'matrix(0.94, 0, 0, 0.86, 4, 9)');
  await page.getByRole('button',{name:'재생',exact:true}).evaluate(button=>button.blur());
  await page.locator('.player').screenshot({path:out+'play-key-pressed.png'});
  checks.push('play key stays visibly recessed after story closes');
  await page.getByRole('button',{name:'빨리 감기',exact:true}).click();
  assert.equal(await key(2).getAttribute('data-latched'),'true');assert.equal(await latched(),1);
  assert.equal(await matrix(0),'matrix(1, 0, 0, 1, 0, 0)');
  await page.locator('.player').screenshot({path:out+'forward-key-pressed.png'});
  await page.getByRole('button',{name:'되감기',exact:true}).click();
  assert.equal(await key(3).getAttribute('data-latched'),'true');assert.equal(await latched(),1);
  checks.push('fast-forward and rewind release the previous key');
  const stop=await page.getByRole('button',{name:'정지',exact:true}).boundingBox();
  await page.mouse.move(stop.x+stop.width/2,stop.y+stop.height/2);await page.mouse.down();
  assert.equal(await matrix(1),'matrix(0.94, 0, 0, 0.86, 4, 9)');
  await page.locator('.player').screenshot({path:out+'stop-key-held.png'});
  await page.mouse.up();
  assert.equal(await latched(),0);assert.equal(await matrix(1),'matrix(1, 0, 0, 1, 0, 0)');
  assert.equal(await page.locator('.player').getAttribute('data-state'),'stopped');
  checks.push('stop depresses while held, then releases all keys');
  await page.getByRole('button',{name:'빨리 감기',exact:true}).focus();await page.keyboard.press('Enter');
  assert.equal(await key(2).getAttribute('data-latched'),'true');
  await page.getByRole('button',{name:'꺼내기 ⏏',exact:true}).click();assert.equal(await latched(),0);
  checks.push('keyboard activation and eject release');
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  mobile.on('pageerror',e=>errors.push(e.message));
  await mobile.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
  await mobile.getByRole('button',{name:'재생',exact:true}).tap();await mobile.keyboard.press('Escape');
  assert.equal(await mobile.locator('.mechanical-key[data-key-index="0"]').getAttribute('data-latched'),'true');
  await mobile.getByRole('button',{name:'재생',exact:true}).evaluate(button=>button.blur());
  await mobile.locator('.player').screenshot({path:out+'mobile-play-key.png'});
  await mobile.getByRole('button',{name:'정지',exact:true}).tap();
  assert.equal(await mobile.locator('.mechanical-key[data-latched="true"]').count(),0);
  checks.push('mobile tap play and stop');
  assert.deepEqual(errors,[]);
  fs.writeFileSync(out+'keys-qa.json',JSON.stringify({passed:true,checks,errors},null,2));
  console.log(JSON.stringify({passed:true,checks,errors}));
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
